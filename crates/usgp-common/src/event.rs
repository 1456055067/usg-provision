//! Audit events with a fixed AU-3 field set.
//!
//! Every event is one tracing event on target [`AUDIT_TARGET`] at INFO.
//! [`crate::telemetry::init`] always passes this target through, whatever
//! the configured log level, so audit records cannot be filtered away by
//! a quiet log setting. With [`crate::telemetry::LogFormat::Json`] each
//! event is one JSON line with these top-level keys:
//!
//! | Key | AU-3 element | Source |
//! |-----|--------------|--------|
//! | `timestamp` | when (UTC, RFC 3339) | subscriber clock |
//! | `event` | what | [`AuditEvent::event`] |
//! | `outcome` | outcome | [`AuditEvent::outcome`] |
//! | `component` | who (service identity) / source | [`AuditEvent::component`] |
//! | `node_name` | where | [`set_node_name`], if set |
//! | `interface`, `local_addr` | where | event fields, if set |
//! | `peer` | source / subject | event field, if set |
//! | `claimed_mac`, `claimed_guid` | subject identity **as claimed** (never authenticated, REQ-BOOT-045) | event fields, if set |
//! | `detail` | additional information | a JSON object, carried as a string |
//!
//! `detail` keys are chosen by the caller at run time, and tracing fields
//! need static names, so the detail pairs are rendered as one JSON object
//! text (keys and values JSON-escaped) in a single `detail` field.
//!
//! Callers must never put secrets in any field. M1 has no secrets (plan
//! section 6).

// COMPLIANCE MAPPING:
// - NIST 800-53: AU-2 (Event Logging) - one named event per auditable action.
// - NIST 800-53: AU-3 (Content of Audit Records) - fixed who/what/when/
//   where/outcome fields on every record.
// - NIST 800-53: AU-12 (Audit Record Generation) - generated by each
//   component through this single function.
// - NIST 800-53: IA-3 - NOT MET on TB-1: PXE devices are unauthenticated
//   by the standard; MAC and GUID are recorded as claimed labels only,
//   never as authenticators. Compensating controls and risk acceptance:
//   docs/compliance/POAM.md (IA-3 on TB-1).
// - SPEC: specs/boot-network.md#REQ-BOOT-045, #REQ-BOOT-052

// POAM: AU-9 (Protection of Audit Information) - events go to stdout only
// in M1; the tamper-evident store (usgp-audit) arrives in M2.

use std::fmt::Write as _;
use std::net::SocketAddr;
use std::sync::OnceLock;

/// Tracing target used for every audit event.
pub const AUDIT_TARGET: &str = "audit";

/// Result of the audited action.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
#[non_exhaustive]
pub enum Outcome {
    /// The action completed.
    Success,
    /// The action was attempted and failed.
    Failure,
    /// The action was refused by policy or validation.
    Refused,
    /// Input was discarded without a reply.
    Dropped,
}

impl Outcome {
    /// The text written in the `outcome` field.
    #[must_use]
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Success => "success",
            Self::Failure => "failure",
            Self::Refused => "refused",
            Self::Dropped => "dropped",
        }
    }
}

impl std::fmt::Display for Outcome {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(self.as_str())
    }
}

/// One audit record.
///
/// Build with [`AuditEvent::new`] and struct-update syntax:
///
/// ```
/// use usgp_common::event::{AuditEvent, Outcome};
/// let detail = [("file", "usgp-test-payload.efi".to_owned())];
/// let e = AuditEvent {
///     interface: Some("eth1"),
///     detail: &detail,
///     ..AuditEvent::new("boot.file.verified", Outcome::Success, "usgp-relay")
/// };
/// usgp_common::event::emit(&e);
/// ```
#[derive(Debug, Clone)]
pub struct AuditEvent<'a> {
    /// Event name, for example `relay.start` (plan section 7).
    pub event: &'a str,
    /// Outcome of the action.
    pub outcome: Outcome,
    /// Emitting component (`usgp-relay`, `usgp-cli`); the "who" for
    /// service events.
    pub component: &'a str,
    /// Network interface name, if the event concerns one.
    pub interface: Option<&'a str>,
    /// Local socket address, if the event concerns one.
    pub local_addr: Option<SocketAddr>,
    /// Remote peer, if any.
    pub peer: Option<SocketAddr>,
    /// Hardware address the device claimed (unauthenticated).
    pub claimed_mac: Option<String>,
    /// Machine GUID the device claimed (unauthenticated).
    pub claimed_guid: Option<String>,
    /// Extra key/value detail, rendered as a JSON object.
    pub detail: &'a [(&'a str, String)],
}

impl<'a> AuditEvent<'a> {
    /// An event with every optional field empty.
    #[must_use]
    pub const fn new(event: &'a str, outcome: Outcome, component: &'a str) -> Self {
        Self {
            event,
            outcome,
            component,
            interface: None,
            local_addr: None,
            peer: None,
            claimed_mac: None,
            claimed_guid: None,
            detail: &[],
        }
    }
}

static NODE_NAME: OnceLock<String> = OnceLock::new();

/// Sets the process-wide `node_name` written on every event (AU-3
/// "where"). The first call wins; returns `false` if a name was already
/// set. The caller validates the name (relay config: at most 64 chars).
pub fn set_node_name(name: &str) -> bool {
    NODE_NAME.set(name.to_owned()).is_ok()
}

/// The process-wide node name, if set.
#[must_use]
pub fn node_name() -> Option<&'static str> {
    NODE_NAME.get().map(String::as_str)
}

/// Emits `e` on the [`AUDIT_TARGET`] tracing target.
pub fn emit(e: &AuditEvent<'_>) {
    let detail = render_detail(e.detail);
    tracing::info!(
        target: AUDIT_TARGET,
        event = e.event,
        outcome = e.outcome.as_str(),
        component = e.component,
        node_name = node_name(),
        interface = e.interface,
        local_addr = e.local_addr.map(tracing::field::display),
        peer = e.peer.map(tracing::field::display),
        claimed_mac = e.claimed_mac.as_deref(),
        claimed_guid = e.claimed_guid.as_deref(),
        detail = detail.as_str(),
    );
}

/// Renders detail pairs as a JSON object text, in the given order.
#[must_use]
pub fn render_detail(pairs: &[(&str, String)]) -> String {
    let mut out = String::from("{");
    for (i, (k, v)) in pairs.iter().enumerate() {
        if i > 0 {
            out.push(',');
        }
        push_json_string(&mut out, k);
        out.push(':');
        push_json_string(&mut out, v);
    }
    out.push('}');
    out
}

/// Appends `s` as a JSON string literal (RFC 8259 §7). Control characters
/// are escaped, so a device-supplied value cannot forge a log line.
fn push_json_string(out: &mut String, s: &str) {
    out.push('"');
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if u32::from(c) < 0x20 || c == '\u{7f}' || c == '\u{2028}' || c == '\u{2029}' => {
                let _ = write!(out, "\\u{:04x}", u32::from(c));
            }
            c => out.push(c),
        }
    }
    out.push('"');
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn outcome_text() {
        assert_eq!(Outcome::Success.as_str(), "success");
        assert_eq!(Outcome::Failure.as_str(), "failure");
        assert_eq!(Outcome::Refused.as_str(), "refused");
        assert_eq!(Outcome::Dropped.to_string(), "dropped");
    }

    #[test]
    fn detail_empty_and_ordered() {
        assert_eq!(render_detail(&[]), "{}");
        let d = [("b", "2".to_owned()), ("a", "1".to_owned())];
        assert_eq!(render_detail(&d), r#"{"b":"2","a":"1"}"#);
    }

    #[test]
    fn detail_escapes_control_and_quotes() {
        let d = [("k\"", "a\nb\\c\u{1}\u{7f}\u{2028}é".to_owned())];
        assert_eq!(render_detail(&d), r#"{"k\"":"a\nb\\c\u0001\u007f\u2028é"}"#);
    }
}
